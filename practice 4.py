# In Python, loops are used to repeat a block of
# code multiple times.

# 1) W.A.P to print numbers from 1 to 10
# using while loop

i = 1

while i <= 10:
    print(i)
    i += 1

print("Question 1 complete")


# 2) W.A.P to print numbers from 10 down
# to 1 using a while loop

i = 10

while i >= 1:
    print(i)
    i = i - 1
print("Quest 2 complete")